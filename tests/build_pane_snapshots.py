"""Build the pane's recorded-data snapshots with the read module; no source writes.

Each snapshot is the unchanged output of read_session over one recorded fixture,
or over baseline.json with one labelled case from in-progress-cases.json applied
exactly as tests/test_in_progress.py applies it. Nothing is edited after the read.

    python3 tests/build_pane_snapshots.py            # rewrite mod/hooks/snapshots.ts
    python3 tests/build_pane_snapshots.py --check    # exit 1 when the file is stale
    python3 tests/build_pane_snapshots.py --frontend-origin <verified origin> --out <file>

--frontend-origin is the configured frontend address passed to the read module,
which builds the project page from it; without it a project has no page. The
committed file is built without one.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'src'))
from legacy_reader import RecordedReaders, Session, read_session  # noqa: E402

FIXTURES = ROOT / 'tests' / 'fixtures'
OUT = ROOT / 'mod' / 'hooks' / 'snapshots.ts'
SESSION = Session('codex', '00000000-0000-4000-8000-000000000001')
OBSERVED_AT = '2026-10-14T12:00:00Z'

# name -> (fixture file, in-progress case or None, what the snapshot shows)
SNAPSHOTS = {
    'several-rows': ('baseline.json', 'several', 'Header, three bars and two in-progress rows with long cards.'),
    'nothing-in-progress': ('baseline.json', 'empty', 'Complete reads with no in-progress tickets.'),
    'no-scope': ('baseline.json', 'no-scope', 'No scope yet; slate bar and one claimed row remain.'),
    'hidden-bars': ('no-sets.json', None, 'Stated objective with no milestone, epic or slate; in-progress ledger not recorded.'),
    'no-slate': ('baseline.json', 'no-slate-claim', 'Slate bar hidden; one claimed row.'),
    'couldnt-load-scope': ('baseline.json', 'failed-naming', 'Naming read failed: scope, project, milestone and their bars unavailable.'),
    'couldnt-load-epic': ('children-partial.json', None, 'Partial sub-issue read: epic bar unavailable.'),
    'couldnt-load-in-progress': ('baseline.json', 'runs-failed', 'Run-ledger read failed: in-progress section unavailable.'),
    'couldnt-load-card': ('baseline.json', 'failed-blockers', 'Blocker read failed: the row stays, its card is unavailable.'),
    'empty-sets': ('empty.json', None, 'Complete empty progress sets: no tickets, no fill.'),
    'no-project': ('no-project.json', None, 'No project-store record: Project: Not recorded.'),
    'automatic-scope': ('scope-automatic.json', None, 'Scope from the automatic session title.'),
    'ticket-set': ('cross-ticket-set.json', None, 'Cross-repository ticket-set scope: project, milestone and epic hidden.'),
    'cross-repository': ('baseline.json', 'cross-repository', 'Row whose repository differs from the scope repository.'),
    'missing-card': ('baseline.json', 'missing-card', 'Row card with every detail not recorded and no page.'),
}
DEFAULT = 'several-rows'


def apply_case(name):
    case = next(c for c in json.loads((FIXTURES / 'in-progress-cases.json').read_text())['cases']
                if c['name'] == name)
    data = json.loads((FIXTURES / case['parent']).read_text())
    for change in case['changes']:
        tokens = [s.replace('~1', '/').replace('~0', '~') for s in change['path'].split('/')[1:]]
        target = data
        for token in tokens[:-1]:
            target = target[token]
        if change['op'] == 'remove':
            del target[tokens[-1]]
        else:
            target[tokens[-1]] = change['value']
    return case['parent'], data


def build(frontend_origin=None):
    entries = {}
    for name, (fixture, case, purpose) in SNAPSHOTS.items():
        if case is None:
            parent, records = fixture, json.loads((FIXTURES / fixture).read_text())
        else:
            parent, records = apply_case(case)
            assert parent == fixture, (name, parent)
        snapshot = read_session(SESSION, RecordedReaders(records), observed_at=OBSERVED_AT,
                                frontend_origin=frontend_origin)
        entries[name] = dict(name=name, fixture=fixture, case=case, purpose=purpose, snapshot=snapshot)
    return entries


def render(entries):
    body = json.dumps(entries, indent=1, ensure_ascii=False, sort_keys=True)
    return ('// Generated by tests/build_pane_snapshots.py from tests/fixtures; do not edit.\n'
            '// Each snapshot is read_session output over the named fixture (and in-progress case).\n'
            "import type { SnapshotEntry } from './snapshot'\n\n"
            f"export const DEFAULT_SNAPSHOT = {json.dumps(DEFAULT)}\n\n"
            f'const DATA = {body}\n\n'
            '// The pane reads a subset of each snapshot; evidence and read times stay in it, never shown.\n'
            'export const SNAPSHOTS = DATA as unknown as Record<string, SnapshotEntry>\n')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--frontend-origin')
    parser.add_argument('--out', type=Path, default=OUT)
    args = parser.parse_args()
    text = render(build(args.frontend_origin))
    if args.check:
        if args.out.read_text() != text:
            sys.exit(f'{args.out} is stale; run python3 tests/build_pane_snapshots.py')
        return
    args.out.write_text(text)


if __name__ == '__main__':
    main()
